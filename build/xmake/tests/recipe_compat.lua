function main()
    local root = path.absolute(".")
    local compat = import("recipe_compat", {rootdir = path.join(root, "build/xmake"), anonymous = true})
    local R = compat.new({root = root, current = root})
    local checks = 0
    local function check(value) assert(value); checks = checks + 1 end
    check(not R.truthy({}) and not R.truthy("") and not R.truthy(0))
    check(R.truthy({false}) and R.truthy("0"))
    local a, b = {1}, {2}
    local shared = a
    check(R.iadd(a, b) == shared and #shared == 2 and shared[2] == 2)
    local copy = R.add(a, b)
    check(copy ~= a and #a == 2 and #copy == 3)
    check(R.index(a, 0) == 1 and R.index(a, -1) == 2)
    R.setindex(a, 0, 3); check(a[1] == 3)
    R.insert(a, 1, 7); check(a[2] == 7)
    R.remove(a, 7); check(#a == 2)
    check(R.contains("hello", "ell") and R.contains({3, 2}, 2))
    check(R.startswith("/fp:fast", {"/fp:", "-Ofast"}))
    check(not R.startswith("fine", {"bad", "no"}) and R.endswith("a.cpp", ".cpp"))
    check(R.replace("a\\b\\c", "\\", "/") == "a/b/c")
    check(R.join(R.split("a,,b", ","), ",") == "a,,b")
    check(R.strip("  x \n") == "x" and R.format("platform '{}'", "win") == "platform 'win'")
    check(R.int("-1.9") == -1)
    check(R.enumerate({"a"})[1][1] == 0)
    check(R.map(R.str, {1, false})[2] == "False")
    check(R.get({key = false}, "key", true) == false)
    local ordered = {b = 2, a = 1, __order = {"b", "a"}}
    check(R.items(ordered)[1][1] == "b")
    check(R.isinstance("x", {"str", "bytes"}))
    check(R.repr({"x", "y"}) == "['x', 'y']")
    check(#R.flatten({{1, 2}, {library = "foo"}}) == 3)
    check(R.re.match("([0-9]*).([0-9]*).([0-9]*)-?([0-9.+]*)", "24.2.1"):group(1) == "24")
    check(R.Path("a/b.cpp").stem == "b")
    check(tostring(R.div(R.Path("a"), "b")):gsub("\\", "/") == "a/b")
    check(R.Path("build/xmake/recipe_compat.lua"):is_file())
    local bits = R.dict({[8] = "eight", [12] = "twelve"})
    check(R.index(bits, 8) == "eight")
    R.setindex(bits, 16, "sixteen")
    check(R.index(bits, 16) == "sixteen" and R.len(bits) == 3)
    check(R.contains(bits, 8) and not R.contains(bits, "eight"))
    check(#R.iter(bits) == 3)
    local adjacent = R.dict({[1] = "one", [2] = "two"})
    check(R.index(adjacent, 1) == "one" and R.iter(adjacent)[1] == 1)
    check(not R.truthy(R.dict({})))
    local directories = R.os.walk("build/xmake/tests")
    check(#directories >= 1 and directories[1][1]:endswith("tests"))
    check(#R.os.walk(".build/does-not-exist-qualification") == 0)
    print("LUA_RECIPE_COMPAT_CHECKS=" .. checks)
end
