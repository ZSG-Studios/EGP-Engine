    local R = graph.compat
    local env
    env = graph:use("env")
    env:sources(env.servers_sources, "instance_uniforms.cpp")
    env:sources(env.servers_sources, "renderer_canvas_cull.cpp")
    env:sources(env.servers_sources, "renderer_canvas_render.cpp")
    env:sources(env.servers_sources, "renderer_compositor.cpp")
    env:sources(env.servers_sources, "renderer_geometry_instance.cpp")
    env:sources(env.servers_sources, "renderer_scene_cull.cpp")
    env:sources(env.servers_sources, "renderer_scene_occlusion_cull.cpp")
    env:sources(env.servers_sources, "renderer_scene_render.cpp")
    env:sources(env.servers_sources, "renderer_viewport.cpp")
    env:sources(env.servers_sources, "rendering_context_driver.cpp")
    env:sources(env.servers_sources, "rendering_light_culler.cpp")
    env:sources(env.servers_sources, "rendering_method.cpp")
    env:sources(env.servers_sources, "rendering_server.cpp")
    env:sources(env.servers_sources, "rendering_server_default.cpp")
    env:sources(env.servers_sources, "rendering_server_globals.cpp")
    env:sources(env.servers_sources, "shader_compiler.cpp")
    env:sources(env.servers_sources, "shader_expression.cpp")
    env:sources(env.servers_sources, "shader_include_db.cpp")
    env:sources(env.servers_sources, "shader_language.cpp")
    env:sources(env.servers_sources, "shader_preprocessor.cpp")
    env:sources(env.servers_sources, "shader_types.cpp")
    env:sources(env.servers_sources, "shader_warnings.cpp")
    if R.truthy(R.index(env, "rendering_device")) then
        env:sources(env.servers_sources, "rendering_device.cpp")
        env:sources(env.servers_sources, "rendering_device_binds.cpp")
        env:sources(env.servers_sources, "rendering_device_commons.cpp")
        env:sources(env.servers_sources, "rendering_device_driver.cpp")
        env:sources(env.servers_sources, "rendering_device_graph.cpp")
        env:sources(env.servers_sources, "rendering_shader_container.cpp")
        graph:include("renderer_rd/recipe.lua")
    end
    graph:include("dummy/recipe.lua")
    graph:include("environment/recipe.lua")
    graph:include("storage/recipe.lua")
end
