function main()
    local root=os.curdir()
    local fence=import('build.xmake.api_fence',{rootdir=root})
    local folder=path.join(root,'.build/xmake-api-fence-test'); os.mkdir(folder)
    local api,header=path.join(folder,'api.json'),path.join(folder,'sdk.h')
    io.writefile(api,'{"classes":[]}'); io.writefile(header,'exact matching embedded SDK')
    local receipt={signature='source-binary-signature',api_hash=hash.sha256(api),header_hash=hash.sha256(header)}
    assert(fence.valid(receipt,receipt.signature,api,header),'Matching API/SDK cache must be reusable')
    assert(not fence.valid(receipt,'changed-source',api,header),'Changed bootstrap/source must regenerate SDK')
    io.writefile(api,'stale or corrupted API')
    assert(not fence.valid(receipt,receipt.signature,api,header),'Corrupted restored API must not pass cache fence')
    io.writefile(api,'{"classes":[]}'); io.writefile(header,'stale or corrupted SDK')
    assert(not fence.valid(receipt,receipt.signature,api,header),'Corrupted restored SDK must not pass cache fence')
    assert(not fence.valid({signature=receipt.signature,api_hash=receipt.api_hash},receipt.signature,api,header),'Pre-hash legacy receipt must regenerate once')
    local json=import('core.base.json')
    local fake=path.join(folder,'fake_dump.lua')
    local payload=path.join(folder,'fake_payload.json')
    io.writefile(fake,"function main(mode,input) if mode~='empty' then os.cp(input,path.join(os.curdir(),'extension_api.json')) end end\n")
    local function capture(mode,value)
        io.writefile(payload,value or '')
        return fence.dump_fresh(os.programfile(),folder,function(program,args,options)
            assert(args[1]=='--headless' and args[2]=='--dump-extension-api' and options.timeout==120000,'Actual API capture must preserve bootstrap flags and watchdog')
            os.vrunv(program,{'lua',fake,mode,payload},options)
        end)
    end
    local document={header={version_major=4,version_minor=8,version_patch=0,version_status='dev',version_build='custom_build',version_full_name='EGP qualification'},classes={{name='Object'}}}
    local prior_api,prior_header=io.readfile(api),io.readfile(header)
    assert(not utils.trycall(function() capture('empty') end),'Exit-zero/no-output bootstrap must not reuse old API')
    assert(not utils.trycall(function() capture('malformed','{') end),'Malformed JSON must not publish')
    local badheader=table.clone(document); badheader.header={version_major=4}
    assert(not utils.trycall(function() capture('badheader',json.encode(badheader)) end),'Incomplete API header must fail')
    local badclass=table.clone(document); badclass.classes={{name='not a class name'}}
    assert(not utils.trycall(function() capture('badclass',json.encode(badclass)) end),'Invalid API class shape must fail')
    local duplicate=table.clone(document); duplicate.classes={{name='Object'},{name='Object'}}
    assert(not utils.trycall(function() capture('duplicate',json.encode(duplicate)) end),'Duplicate API class names must fail')
    assert(io.readfile(api)==prior_api and io.readfile(header)==prior_header,'Failed fresh dumps must preserve published API and SDK')
    local fresh=capture('valid',json.encode(document))
    assert(not utils.trycall(function() fence.publish(fresh,api,header,function(prepared) io.writefile(prepared,'partial SDK'); raise('injected generator failure') end) end),'Generator failure must abort publication')
    assert(io.readfile(api)==prior_api and io.readfile(header)==prior_header,'Generator failure must roll back partial SDK and preserve previous API')
    assert(not utils.trycall(function() fence.publish(fresh,api,header,function() end) end),'Successful no-output SDK generator must not reuse the old header')
    fence.publish(fresh,api,header,function(prepared) io.writefile(prepared,'new complete SDK') end)
    assert(io.readfile(api)==io.readfile(fresh) and io.readfile(header)=='new complete SDK','Successful generation must publish matching API and SDK')
    local implementation=path.join(folder,'implementation.lua')
    local template=path.join(folder,'template.h')
    local renamed=path.join(folder,'renamed.h')
    io.writefile(implementation,'native generator implementation')
    io.writefile(template,'same exact SDK contents'); io.writefile(renamed,'same exact SDK contents')
    local initial=fence.signature(fake,{implementation},{{path=template},{value='64',literal=true}},root)
    assert(initial==fence.signature(fake,{implementation},{{value='64',literal=true},{path=template}},root),'Input enumeration order must not change signature')
    assert(initial~=fence.signature(fake,{implementation},{{path=renamed},{value='64',literal=true}},root),'Identical bytes under a renamed SDK archive entry must invalidate cache')
    assert(initial~=fence.signature(fake,{implementation},{{path=template},{value='32',literal=true}},root),'SDK ABI literal changes must invalidate cache')
    io.writefile(template,'changed SDK contents')
    assert(initial~=fence.signature(fake,{implementation},{{path=template},{value='64',literal=true}},root),'Same-path content changes must invalidate cache')
    local expected=fence.signature(fake,{implementation},{{path=template}},root)
    os.cd(folder)
    local ok,result=utils.trycall(function()
        return fence.signature(path.relative(fake,root),{path.relative(implementation,root)},{{path=path.relative(template,root)}},root)
    end)
    os.cd(root)
    assert(ok and result==expected,'Explicit root must resolve relative inputs independently of caller working directory')
    print('XMAKE_API_FENCE_PASS 20')
end
