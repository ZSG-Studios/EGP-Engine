set_xmakever('3.1.1')
set_languages('cxx17')
target('generated_header_probe')
    set_kind('binary')
    on_load(function(target)
        local root=path.absolute('../../../..',os.projectdir())
        local directory=path.absolute(import('core.project.config').builddir(),os.projectdir())
        local generated=path.join(directory,'generated')
        local header=path.join(directory,'original/platform/linuxbsd/wayland/embedder.h')
        local protocol=path.join(generated,'platform/linuxbsd/wayland/protocol/wayland.gen.h')
        local source=path.join(directory,'editor/consumer.cpp')
        os.mkdir(path.directory(header)); os.mkdir(path.directory(protocol)); os.mkdir(path.directory(source))
        io.writefile(header,'#include "protocol/wayland.gen.h"\n')
        io.writefile(protocol,'#define GENERATED_WAYLAND_VALUE 37\n')
        io.writefile(source,'#include "embedder.h"\nint main(){return GENERATED_WAYLAND_VALUE==37?0:1;}\n')
        target:add('includedirs',path.directory(header),generated)
        import('build.xmake.generated_headers',{rootdir=root}).configure(target,{platform='linuxbsd',wayland=true},generated)
        target:add('files',source)
        local disabled={}
        function disabled:add(_,value) self.value=value end
        import('build.xmake.generated_headers',{rootdir=root}).configure(disabled,{platform='linuxbsd',wayland=false},generated)
        assert(disabled.value==nil,'Disabled Wayland must not add its generated include directory')
        import('build.xmake.generated_headers',{rootdir=root}).configure(disabled,{platform='windows'},generated)
        assert(disabled.value==nil,'Other platforms must not add Wayland include paths')
        print('NATIVE_GENERATED_HEADER_POLICY_CHECKS=2')
    end)
