-- Exercise the public host-tools entry point and installed native SDK detector.
function main()
    local root=os.curdir()
    local hosts=import('build.xmake.platforms.host',{rootdir=root})
    local compressor,zipper=import('build.xmake.generate',{rootdir=root}).tools(root)
    assert(os.isfile(compressor) and os.isfile(zipper),'The public host-tools entry point must accept omitted options')
    local directory=path.join(root,'.build/xmake-host-sdk-fixture')
    local selected,decoy=path.join(directory,'selected-mingw64'),path.join(directory,'Git SDK with spaces/mingw64')
    os.mkdir(path.join(selected,'bin'))
    os.mkdir(path.join(decoy,'bin'))
    local executable='x86_64-w64-mingw32-gcc' .. (os.host()=='windows' and '.exe' or '')
    io.writefile(path.join(selected,'bin',executable),'SDK discovery sentinel, never executed')
    io.writefile(path.join(decoy,'bin',executable),'PATH decoy, never executed')
    local oldpath=os.getenv('PATH')
    local oldroot=os.getenv('EGP_MINGW_ROOT')
    os.setenv('PATH',path.join(decoy,'bin') .. (os.host()=='windows' and ';' or ':') .. oldpath)
    os.setenv('EGP_MINGW_ROOT',selected)
    local args=hosts.configure_arguments({plat='mingw'},{})
    assert(#args==1 and args[1]=='--mingw=' .. path.absolute(selected))
    local explicit=args[1]:sub(#'--mingw='+1)
    local detector=import('detect.sdks.find_mingw')
    local sdk=assert(detector(explicit,{force=true,arch='x86_64'}))
    assert(path.absolute(sdk.sdkdir)==path.absolute(selected),'Explicit installed SDK must beat Git PATH decoy')
    assert(path.absolute(sdk.bindir)==path.absolute(path.join(selected,'bin')))
    assert(#hosts.configure_arguments({plat='windows'},{})==0,'MSVC must ignore the MinGW override')
    assert(hosts.configure_arguments({plat='mingw'},{mingw=decoy})[1]=='--mingw=' .. path.absolute(decoy),'Explicit caller SDK takes precedence over the CI environment')
    local ok=utils.trycall(function() hosts.configure_arguments({plat='mingw'},{},path.join(directory,'missing')) end)
    assert(not ok,'An invalid configured SDK must fail before unrelated PATH fallback')
    local config=import('core.project.config')
    config.set('mingw',decoy,{force=true})
    local hostargs=hosts.configure_arguments({plat='mingw'},{},config.get('mingw'))
    assert(hostargs[1]=='--mingw=' .. path.absolute(decoy),'The built-in manual SDK option must propagate to isolated generator tools')
    local json=import('core.base.json')
    local stdout=os.iorunv(os.programfile(),{'lua',path.join(root,'misc/scripts/build_egp.lua'),'windows','template_release','1',path.join(directory,'cache'),json.encode({'use_mingw=yes','mingw=' .. decoy}),'dry-run'},{curdir=root})
    local first=assert(stdout:match('([^\r\n]+)'))
    local argv=os.argv(first)
    local selected_count=0
    for _, argument in ipairs(argv) do
        if argument:startswith('--mingw=') then
            selected_count=selected_count+1
            assert(argument=='--mingw=' .. path.absolute(decoy),'Launcher quoting must preserve the entire SDK path with spaces')
        end
    end
    assert(selected_count==1,'The actual launcher must emit exactly one explicit SDK override')
    assert(first:find('--toolchain=mingw',1,true),'Manual SDK selection must retain the GNU toolchain')
    os.setenv('PATH',oldpath)
    os.setenv('EGP_MINGW_ROOT',oldroot)
    print('NATIVE_HOST_SDK_CHECKS=11')
end
