function main()
    local validator=import("misc.scripts.validate_egp_unit_summary",{rootdir=os.curdir()})
    local checks=0
    local function check(value,message) assert(value,message); checks=checks+1 end
    local function rejected(text)
        local ok=utils.trycall(function() return validator.parse(text) end)
        check(not ok,"Incomplete or failed native test evidence must be rejected")
    end
    local valid="[doctest] test cases: 1391 | 1391 passed | 0 failed | 3 skipped\n[doctest] assertions: 318582 | 318582 passed | 0 failed |\n[doctest] Status: SUCCESS!\n"
    local result=validator.parse(valid)
    check(result.passed and result.test_cases==1391 and result.assertions==318582,"Exact actual native counts must be retained")
    check(validator.parse(valid:gsub("%[doctest%]","\27[36m[doctest]\27[0m")).passed,"Existing forced ANSI colors must remain supported")
    rejected("ERROR: Condition \"da.is_null()\" is true. Returning: 0\n at: test_main (tests/test_main.cpp:97)\n")
    rejected("[doctest] doctest version is 2.4.11\n")
    rejected(valid:gsub("%[doctest%] assertions:[^\n]+\n",""))
    rejected(valid:gsub("%[doctest%] Status:[^\n]+\n",""))
    rejected(valid:gsub("1391 | 1391 passed | 0 failed","1391 | 1389 passed | 2 failed"))
    rejected(valid:gsub("318582 | 318582 passed | 0 failed","318582 | 318577 passed | 5 failed"))
    rejected(valid:gsub("SUCCESS","FAILURE"))
    rejected(valid:gsub("1391 | 1391 passed","0 | 0 passed"))
    rejected(valid:gsub("318582 | 318582 passed","0 | 0 passed"))
    rejected(valid..valid)
    local directory=path.join(os.curdir(),".build/unit-summary-fixture")
    os.mkdir(directory)
    local logfile,receiptfile=path.join(directory,"successful.log"),path.join(directory,"receipt.json")
    io.writefile(logfile,valid)
    validator.main(logfile,receiptfile)
    local saved=import("core.base.json").loadfile(receiptfile)
    check(saved.passed and saved.test_cases==1391 and saved.assertions==318582 and #saved.log_sha256==64,"Public log validator must persist exact counts and evidence hash")
    print("NATIVE_UNIT_SUMMARY_CHECKS="..checks)
end
