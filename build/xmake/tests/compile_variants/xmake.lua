set_xmakever('3.1.1')
set_languages('c17')
target('egp_compile_variants_probe')
    set_kind('binary')
    add_files('main.c')
    on_load(function(target)
        local config=import('core.project.config')
        local root=path.absolute('../../../..',os.projectdir())
        local generated=path.join(path.absolute(config.builddir(),os.projectdir()),'generated')
        local variants=import('build.xmake.compile_variants',{rootdir=root})
        local source=path.join(os.projectdir(),'variant.c')
        local policy8={CPPDEFINES={'FLAVOR=8'},nested={a='first',b='second'}}
        local policy12={CPPDEFINES={'FLAVOR=12'},nested={b='second',a='first'}}
        local first=variants.file(target,{policy=policy8},source,generated)
        target:add('files',first,{defines={'FLAVOR=8'}})
        local second=variants.file(target,{policy=policy12},source,generated)
        target:add('files',second,{defines={'FLAVOR=12'}})
        assert(first==source and second~=source,'Ordinary cache identity must remain; second policy needs a separate translation unit')
        assert(variants.file(target,{policy={nested={b='second',a='first'},CPPDEFINES={'FLAVOR=8'}}},source,generated)==first,'Policy key enumeration must not create a new compilation')
        assert(variants.file(target,{policy=policy12},source,generated)==second,'Repeated policy must reuse stable translation unit')
        local jpeg=path.join(root,'thirdparty/libjpeg-turbo/src/jutils.c')
        for _, bits in ipairs({8,12}) do
            local filename=variants.file(target,{policy={CPPDEFINES={'BITS_IN_JSAMPLE=' .. bits}}},jpeg,generated)
            target:add('files',filename,{defines={'BITS_IN_JSAMPLE=' .. bits}})
        end
        target:add('includedirs',path.join(root,'thirdparty/libjpeg-turbo/src'))
        local assembly=path.join(generated,'unsupported.S')
        variants.file(target,{policy={ASFLAGS={'first'}}},assembly,generated)
        assert(not utils.trycall(function() variants.file(target,{policy={ASFLAGS={'second'}}},assembly,generated) end),'Unsupported assembly variants must fail clearly')
        import('build.xmake.generated_objects',{rootdir=root}).configure(target,generated)
        target:data_set('egp.variant_sources',{first,second,jpeg})
    end)
    before_build(function(target)
        local seen={}
        for _, filename in ipairs(target:objectfiles()) do assert(not seen[filename],'Policy variants must have distinct object identities'); seen[filename]=true end
        assert(#target:objectfiles()==5,'Both synthetic and actual JPEG8/12 translation units must compile')
        local config=import('core.project.config')
        import('core.base.json').savefile(path.join(path.absolute(config.builddir(),os.projectdir()),'linked-objects.json'),target:objectfiles())
        print('NATIVE_COMPILE_VARIANT_GRAPH_CHECKS=6')
    end)
target_end()
