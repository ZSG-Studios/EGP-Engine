set_project("egp-native-codegen-tools")
set_version("1.0.0")
set_xmakever("3.1.1")
set_languages("c17", "cxx17")
add_rules("mode.debug", "mode.release")
option("egp_mingw_clang")
    set_default(false)
    set_showmenu(true)
    set_description("Use LLVM for the selected MinGW native code-generation host")
option_end()
rule("egp.codegen_host")
    on_load(function(target)
        if is_plat("mingw") and has_config("egp_mingw_clang") then target:set("toolchains", "mingw", {clang=true}) end
    end)
rule_end()
target("egp_compress")
    add_rules("egp.codegen_host")
    set_kind("binary")
    set_default(true)
    set_targetdir("$(builddir)/bin")
    add_files("compress.cpp")
    add_includedirs("../../../thirdparty/zlib")
    for _, name in ipairs({"adler32", "compress", "crc32", "deflate", "trees", "zutil"}) do
        add_files("../../../thirdparty/zlib/" .. name .. ".c")
    end
    if is_plat("windows") then add_defines("_CRT_SECURE_NO_WARNINGS") end
target("egp_zip")
    add_rules("egp.codegen_host")
    set_kind("binary")
    set_targetdir("$(builddir)/bin")
    add_files("zip.cpp")
    add_includedirs("../../../thirdparty/zlib")
    for _, name in ipairs({"adler32", "compress", "crc32", "deflate", "trees", "zutil"}) do
        add_files("../../../thirdparty/zlib/" .. name .. ".c")
    end
